import { useLayoutEffect, useRef, useState, type RefObject } from "react";

/** The rendered width of an element, kept current with a ResizeObserver. `fallback` is used until the first measurement. */
export function useElementWidth<T extends HTMLElement>(fallback = 860): [RefObject<T | null>, number] {
  const ref = useRef<T>(null);
  const [width, setWidth] = useState(fallback);
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const measure = (): void => {
      const w = Math.round(el.getBoundingClientRect().width);
      if (w > 0) setWidth(w);
    };
    measure();
    if (typeof ResizeObserver === "undefined") return;
    const observer = new ResizeObserver(measure);
    observer.observe(el);
    return () => observer.disconnect();
  }, []);
  return [ref, width];
}
