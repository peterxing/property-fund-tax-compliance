// Renders docs/rules/RULE-REGISTER.md from the same register the app's "Rules & sources" workspace shows (domain/portfolio rulesRegister),
// so the document lists exactly the rules, effective dates, sources and confidence levels the engine carries. Write it with
// `npm run docs:rules`; test/docs/rule-register.test.ts fails when the file is out of date.
import { rulesRegister, type RuleRegisterRow } from "../../src/domain/portfolio/index.ts";
import type { Market } from "../../src/domain/types.ts";

export const RULE_REGISTER_PATH = "docs/rules/RULE-REGISTER.md";

const CONFIDENCE_TEXT: Record<RuleRegisterRow["confidence"], string> = {
  VERIFIED: "Verified (primary source)",
  VERIFIED_SECONDARY: "Verified (secondary source only)",
  ASSUMPTION: "Assumption (needs a reviewer's judgement)",
};
const CONFIDENCE_ORDER: ReadonlyArray<RuleRegisterRow["confidence"]> = ["VERIFIED", "VERIFIED_SECONDARY", "ASSUMPTION"];
const MARKET_TITLE: Record<Market, string> = { AU: "Australia", SG: "Singapore" };
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

function day(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${MONTHS[(m ?? 1) - 1]} ${y}`;
}

/** Text safe to drop into markdown prose: no stray HTML, and no line breaks that would end a list item. */
function prose(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\s+/g, " ").trim();
}

function effective(row: RuleRegisterRow): string {
  if (!row.effectiveFrom && !row.effectiveTo) return "No effective dates (applies to every period the engine supports)";
  const from = row.effectiveFrom ? `from ${day(row.effectiveFrom)}` : "start not stated";
  const to = row.effectiveTo ? `to ${day(row.effectiveTo)}` : "until further notice";
  return `${from} ${to}`;
}

function anchor(row: RuleRegisterRow): string {
  return `rule-${row.market.toLowerCase()}-${row.id.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`;
}

function countTable(rows: readonly RuleRegisterRow[]): string[] {
  const domains = [...new Map(rows.map((row) => [`${row.market}:${row.domain}`, row])).values()];
  const out = [
    "| Market | Area | Verified (primary) | Verified (secondary) | Assumption | Total |",
    "| --- | --- | ---: | ---: | ---: | ---: |",
  ];
  for (const sample of domains) {
    const inDomain = rows.filter((row) => row.market === sample.market && row.domain === sample.domain);
    const by = (confidence: RuleRegisterRow["confidence"]) => inDomain.filter((row) => row.confidence === confidence).length;
    out.push(`| ${MARKET_TITLE[sample.market]} | [${prose(sample.domainLabel)}](#${sectionAnchor(sample)}) | ${by("VERIFIED")} | ${by("VERIFIED_SECONDARY")} | ${by("ASSUMPTION")} | ${inDomain.length} |`);
  }
  const all = (confidence: RuleRegisterRow["confidence"]) => rows.filter((row) => row.confidence === confidence).length;
  out.push(`| **All** | | **${all("VERIFIED")}** | **${all("VERIFIED_SECONDARY")}** | **${all("ASSUMPTION")}** | **${rows.length}** |`);
  return out;
}

function sectionAnchor(row: RuleRegisterRow): string {
  return `area-${row.market.toLowerCase()}-${row.domain.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`;
}

function ruleBlock(row: RuleRegisterRow): string[] {
  const out = [
    `#### <a id="${anchor(row)}"></a>${prose(row.title)}`,
    "",
    `* **Rule id:** \`${row.id}\``,
    `* **Effective:** ${effective(row)}`,
    `* **Confidence:** ${CONFIDENCE_TEXT[row.confidence]}`,
    `* **What the engine applies:** ${prose(row.summary)}`,
  ];
  if (row.notes.trim()) out.push(`* **Limits and notes:** ${prose(row.notes)}`);
  out.push("* **Sources:**");
  for (const source of row.sources) {
    const publisher = source.publisher ? `${prose(source.publisher)}, ` : "";
    out.push(`  * [${prose(source.title)}](${source.url.replace(/\s/g, "%20").replace(/\)/g, "%29")}) (${publisher}read ${day(source.retrieved)})`);
  }
  out.push("");
  return out;
}

export function renderRuleRegister(): string {
  const rows = rulesRegister("all").rows;
  const out: string[] = [
    "# Rule register",
    "",
    "<!-- Generated by `npm run docs:rules` from the engine's rule entries (src/engine/registry.ts and src/engine/au/registry.ts). Do not edit by hand: test/docs/rule-register.test.ts fails when this file and the engine disagree. -->",
    "",
    "Every rule the calculation engine carries, with its effective dates, the sources it was read from and how confident the engine's authors are in it. This is the same register as the app's **Rules & sources** workspace, and each rule's id is the one shown there and in calculation breakdowns.",
    "",
    "How to read it:",
    "",
    "* **Verified (primary source):** the rate, threshold or method was read from legislation or the tax authority's own guidance on the date shown against each source.",
    "* **Verified (secondary source only):** corroborated by a reputable secondary source (for example a professional firm's summary) but not yet by a primary source. A reviewer should confirm it against the primary source.",
    "* **Assumption:** a modelling choice or simplification. The app flags these for a tax professional's review, and the calculation documents explain each one.",
    "* **Effective dates** are inclusive. A rule with no end date applies until further notice; the engine refuses to calculate for a date no rule covers rather than guessing.",
    "",
    "The calculation documents in this folder explain how the rules are combined, with worked examples; start at [README.md](README.md).",
    "",
    "## Summary",
    "",
    ...countTable(rows),
    "",
  ];
  for (const market of ["AU", "SG"] as const) {
    out.push(`## ${MARKET_TITLE[market]}`, "");
    const inMarket = rows.filter((row) => row.market === market);
    const domains = [...new Map(inMarket.map((row) => [row.domain, row])).values()];
    for (const sample of domains) {
      const inDomain = inMarket
        .filter((row) => row.domain === sample.domain)
        .sort((a, b) => CONFIDENCE_ORDER.indexOf(a.confidence) - CONFIDENCE_ORDER.indexOf(b.confidence) || a.title.localeCompare(b.title) || a.id.localeCompare(b.id));
      out.push(`### <a id="${sectionAnchor(sample)}"></a>${prose(sample.domainLabel)} (${inDomain.length})`, "");
      for (const row of inDomain) out.push(...ruleBlock(row));
    }
  }
  return `${out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
